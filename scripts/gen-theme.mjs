#!/usr/bin/env node
/**
 * gen-theme.mjs — regenerate the project's CSS token layers from the better-design corpus.
 *
 *   npm run gen:theme
 *
 * Outputs (all generated, all verbatim from the registry — do not hand-edit):
 *   src/tokens.css   the base system's `:root` block, extracted as-is
 *   src/theme-map.css the `@theme inline` mapping Tailwind v4 needs
 *   src/themes.css   [data-theme="…"] override blocks for every switchable system
 *
 * BASE is the project's brand system; the switcher list is what the site can re-skin to.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir, homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, '..', 'src');
const CORPUS = process.env.BD_CORPUS || join(homedir(), 'better-design');
const EXPORT = join(homedir(), '.agents/skills/better-design/scripts/export-themes.mjs');

const BASE = 'slate-light';
/** switcher id → system id in the corpus (the id that ships in the UI is the project's own) */
const SOURCE = { 'slate-light': 'tactile-minimal' };
const srcOf = (id) => SOURCE[id] || id;
/** the exporter's own display name for a corpus system (used in its comment headers) */
const COMMENT_NAMES = { 'tactile-minimal': 'Tactile Minimal' };
const SWITCHABLE = ['slate-light', 'minimal-light', 'pillow-light', 'light-marketplace', 'precision-light', 'editorial-dark'];

// per-system typography, wired to the self-hosted variable fonts
const FONTS = {
  'slate-light': `"Inter Variable", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
  'minimal-light': `"Inter Variable", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
  'pillow-light': `"Inter Variable", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
  'light-marketplace': `"Inter Variable", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
  'precision-light': `"Inter Variable", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
  'editorial-dark': `"Inter Variable", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
  'dark-orange': `"Inter Variable", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
};
/** editorial serif for headlines and prices-in-prose — a roaster reads as a craft brand with a serif */
const DISPLAY = `"Fraunces Variable", "Fraunces", Georgia, "Times New Roman", serif`;
const MONO = `"JetBrains Mono Variable", ui-monospace, SFMono-Regular, Menlo, monospace`;

mkdirSync(SRC, { recursive: true });
const globals = readFileSync(join(CORPUS, 'source', srcOf(BASE), 'globals.css'), 'utf8');

/* 1. base tokens — lift the :root block untouched so values stay authoritative */
const rootMatch = globals.match(/:root\s*\{[\s\S]*?\n\}/);
if (!rootMatch) throw new Error('could not find :root in ' + srcOf(BASE) + '/globals.css');
writeFileSync(join(SRC, 'tokens.css'),
  `/* generated by scripts/gen-theme.mjs from better-design/registry/${srcOf(BASE)}/globals.json\n` +
  `   ${BASE} token sheet — verbatim. Do not edit by hand; run \`npm run gen:theme\`. */\n\n` +
  rootMatch[0] + '\n');

/* 2. @theme inline — the corpus mapping, extended with fonts + spacing rhythm */
const themeMatch = globals.match(/@theme inline\s*\{[\s\S]*?\n\}/);
if (!themeMatch) throw new Error('could not find @theme inline');
let themeBlock = themeMatch[0].replace(/\n\}$/, `
  /* typography — self-hosted variable fonts, switched per design system */
  --font-sans: var(--app-font-sans, ${FONTS[BASE]});
  --font-mono: ${MONO};
  --font-display: ${DISPLAY};
}`);
writeFileSync(join(SRC, 'theme-map.css'), `/* generated by scripts/gen-theme.mjs — do not edit by hand */\n\n` + themeBlock + '\n');

/* 3. switchable themes — straight out of export-themes.mjs */
const tmp = join(tmpdir(), `knuckles-themes-${process.pid}.css`);
execFileSync(process.execPath, [EXPORT, ...SWITCHABLE.map(srcOf), '--out', tmp], { stdio: 'inherit' });
let themes = readFileSync(tmp, 'utf8');
// rename corpus system ids — and the display names in the block comments — to the project's own
const LABELS = { 'tactile-minimal': 'Slate' };
for (const [out, source] of Object.entries(SOURCE)) themes = themes.split(source).join(out);
for (const [source, label] of Object.entries(LABELS)) themes = themes.split(`/* ${COMMENT_NAMES[source]} — `).join(`/* ${label} — `);
// strip the exporter's structural defaults — the app sets those itself
themes = themes.replace(/\/\* structural defaults[\s\S]*?\n\}\n\n/, '');
// add the font override + light/dark hint to each block
themes = themes.replace(/\[data-theme="([a-z-]+)"\] \{/g, (m, id) =>
  `[data-theme="${id}"] {\n  --app-font-sans: ${FONTS[id] || FONTS[BASE]};`);
writeFileSync(join(SRC, 'themes.css'), themes);

const count = (themes.match(/^\[data-theme="/gm) || []).length;
console.log(`\ngenerated: src/tokens.css, src/theme-map.css, src/themes.css (${count} switchable systems, base: ${BASE})`);
